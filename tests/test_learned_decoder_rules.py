def test_only_the_outer_plan_is_rewritten():
    # Parser.select: re-entrant calls (prior turn, clauses) keep the decoder's shapes for follow-up arithmetic; research has no period.
    parser = Parser.__new__(Parser)       # no model: _select is replaced
    plan = {'status': 'planned', 'reason_codes': [], 'queries': [
        {'kind': 'health', 'metrics': ['steps'], 'period': {'kind': 'relative', 'amount': 2, 'unit': 'weeks'}}, {'kind': 'research', 'topic': 'zone-2 training'}]}
    parser._select = lambda req: plan
    req = {'state': {'reference_date': '2026-09-26'}}
    assert parser.select(req)['queries'] == [{**plan['queries'][0], 'period': {'kind': 'relative', 'amount': 14, 'unit': 'days'}}, plan['queries'][1]]
    assert parser.select({**req, '_clause': True}) is plan


