from learned_parser.decode import Parser, calm, contract_period
from learned_parser.parse import AMBIGUOUS, _months_back, parse_rolling, parse_time_span, resolve_period

ROOT = Path(__file__).resolve().parents[1]
REF = date(2026, 9, 26)  # a Saturday


def span(text):
    got = parse_time_span(text, REF)
    return None if got is None else (got[0].isoformat(), got[1].isoformat())


def sentences(text):
    return [m.group(0).strip() for m in Parser.SENTENCE.finditer(text)]


# ---- the serving copy is complete ----

@pytest.mark.parametrize('module', ['learned_parser.decode', 'learned_parser.parse', 'learned_parser.verify'])
def test_every_module_name_a_function_reads_is_defined(module):
    # A dropped constant that only a function reads (SEPARATORS in Parser.split_run) passes the import and fails per request.
    mod = importlib.import_module(module)
    tables, reads = [symtable.symtable(Path(mod.__file__).read_text(encoding='utf-8'), mod.__file__, 'exec')], set()
    while tables:
        table = tables.pop(); tables += table.get_children()
        if table.get_type() == 'function': reads |= {s.get_name() for s in table.get_symbols() if s.is_global() and s.is_referenced()}
    assert sorted(n for n in reads if n not in vars(mod) and not hasattr(builtins, n)) == []


def test_every_parser_attribute_a_method_reads_is_defined():
    # The same breakage inside the class: a dropped class constant (SENTENCE, INTERNAL, SPAN_MIN, ...) or method.
    tree = ast.parse(Path(decode.__file__).read_text(encoding='utf-8'))
    cls = next(n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == 'Parser')
    attrs = [n for n in ast.walk(cls) if isinstance(n, ast.Attribute) and isinstance(n.value, ast.Name) and n.value.id in ('self', 'cls')]
    stored = {n.attr for n in attrs if isinstance(n.ctx, ast.Store)}
    assert sorted({n.attr for n in attrs if isinstance(n.ctx, ast.Load)} - stored - set(dir(Parser))) == []


