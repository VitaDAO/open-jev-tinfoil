"""Deterministic rules of the learned parser as served from the repo (learned_parser/, metadata/learned/; spec v1.8 10g). Model-free.

The serving copy is generated by a sync script that once dropped a module constant read only inside a function: the import still
worked and most requests raised NameError. These tests read the served modules and data files directly."""
import ast
